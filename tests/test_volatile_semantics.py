SYMBOL = "g_control_flags_03000940"
DECLARATION = ("extern struct { u16 display; u8 unknown_02[0x3A]; volatile u8 unknown_3C : 8; "
               "volatile u8 unknown_3D : 8; } " + SYMBOL + ";")
PREPROCESSED = "void func_08028C34(void);\nextern void func_0802A2C0(int);\n"


def assembly(*body, name="func_08028C34"):
    """agbcc-shaped output for one Thumb function with a one-word pool"""
    return ("@ Generated by gcc 2.9-arm-000512 for Thumb/elf\n\t.code\t16\n.gcc2_compiled.:\n.text\n"
            f"\t.align\t2, 0\n\t.globl\t{name}\n\t.type\t {name},function\n\t.thumb_func\n{name}:\n" +
            "".join(f"\t{line}\n" if not line.endswith(":") else f"{line}\n" for line in body) +
            f".L4:\n\t.align\t2, 0\n.L3:\n\t.word\t{SYMBOL}\n.Lfe1:\n"
            f"\t.size\t {name},.Lfe1-{name}\n")


def compare(real, stripped, preprocessed=PREPROCESSED):
    return semantics.compare(real, stripped, preprocessed, SYMBOL, DECLARATION)


class SemanticDiffTests(unittest.TestCase):
    def refused(self, real, stripped, reason):
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(real, stripped)
        self.assertIn(reason, str(caught.exception))

    def test_layout_of_the_pinned_declaration(self):
        self.assertEqual(semantics.object_layout(DECLARATION), (0x3E, {0x3C, 0x3D}))
        shipped = plausible.volatile_allow_entries()[0]["declaration"]
        self.assertEqual(semantics.object_layout(shipped)[1],
                         {0x3C, 0x3D, 0x40, 0x41, 0x43, 0x4A, 0x4B, 0x4C, 0x4D})
        for broken in (DECLARATION.replace(": 8", ": 4"), DECLARATION.replace("u16", "float"),
                       DECLARATION.replace("volatile u8 unknown_3D : 8", "volatile u16 unknown_3D : 16")):
            with self.subTest(declaration=broken), self.assertRaises(semantics.SemanticError):
                semantics.object_layout(broken)

    def test_stripping_touches_only_the_pinned_declaration(self):
        text = "volatile int other;\n" + DECLARATION.replace("; ", ";\n  ") + "\nvolatile u8 *io;\n"
        stripped = semantics.strip_pinned_volatile(text, DECLARATION)
        self.assertEqual(len(stripped), len(text))
        self.assertTrue(stripped.startswith("volatile int other;"))
        self.assertTrue(stripped.endswith("volatile u8 *io;\n"))
        self.assertEqual(stripped.count("volatile"), 2)
        for broken in ("", text + text, text.replace("unknown_3C", "unknown_3E")):
            with self.subTest(text=broken), self.assertRaises(semantics.SemanticError):
                semantics.strip_pinned_volatile(broken, DECLARATION)

    def test_dead_load_before_each_byte_store_is_accepted(self):
        real = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "ldrb\tr0, [r1]", "mov\tr0, #19",
                        "strb\tr0, [r1]", "bx\tlr")
        stripped = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "mov\tr0, #19", "strb\tr0, [r1]",
                            "bx\tlr")
        (result,) = compare(real, stripped)
        self.assertEqual(result, ("func_08028C34", 1, [2], []))
        self.assertIn("read-modify-write loads at [3]",
                      semantics.record(SYMBOL, [result]))

    def test_register_allocation_and_address_arithmetic_may_differ(self):
        real = assembly("ldr\tr3, .L3", "add\tr2, r3, #0", "add\tr2, r2, #61", "ldrb\tr0, [r2]",
                        "mov\tr1, #0", "strb\tr1, [r2]", "sub\tr2, r2, #1", "ldrb\tr0, [r2]",
                        "strb\tr1, [r2]", "bx\tlr")
        stripped = assembly("ldr\tr2, .L3", "add\tr0, r2, #0", "add\tr0, r0, #61", "mov\tr1, #0",
                            "strb\tr1, [r0]", "add\tr0, r2, #0", "add\tr0, r0, #60",
                            "strb\tr1, [r0]", "bx\tlr")
        self.assertEqual(compare(real, stripped)[0][1:], (1, [3, 7], []))

    def test_chained_assignment_re_read_is_accepted(self):
        # `sym.unknown_3C = (sym.unknown_3D = 0);`: volatile re-reads 0x3D
        real = assembly("ldr\tr3, .L3", "add\tr2, r3, #0", "add\tr2, r2, #61", "ldrb\tr0, [r2]",
                        "mov\tr1, #0", "strb\tr1, [r2]", "ldrb\tr0, [r2]", "sub\tr2, r2, #1",
                        "ldrb\tr1, [r2]", "strb\tr0, [r2]", "bx\tlr")
        stripped = assembly("ldr\tr3, .L3", "add\tr2, r3, #61", "mov\tr1, #0", "strb\tr1, [r2]",
                            "sub\tr2, r2, #1", "strb\tr1, [r2]", "bx\tlr")
        self.assertEqual(compare(real, stripped)[0][1:], (1, [3, 8], [6]))
        # the re-read value may only reach pinned byte stores, unchanged:
        # `sym.unknown_3C = (sym.unknown_3D = 0) + 1;` keeps a read the
        # stripped compile does not need
        used = real.replace("ldrb\tr0, [r2]\n\tsub\tr2, r2, #1",
                            "ldrb\tr0, [r2]\n\tadd\tr0, r0, #1\n\tsub\tr2, r2, #1")
        self.assertNotEqual(used, real)
        plus_one = stripped.replace("sub\tr2, r2, #1\n\tstrb\tr1, [r2]",
                                    "sub\tr2, r2, #1\n\tmov\tr1, #1\n\tstrb\tr1, [r2]")
        self.assertNotEqual(plus_one, stripped)
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(used, plus_one)
        self.assertIn("the qualifier added a read", str(caught.exception))

    def test_extra_load_without_its_store_is_refused(self):
        stripped = assembly("ldr\tr1, .L3", "add\tr1, r1, #61", "mov\tr0, #1", "strb\tr0, [r1]",
                            "bx\tlr")
        for name, real in (
                ("bare read", assembly("ldr\tr1, .L3", "add\tr2, r1, #60", "ldrb\tr2, [r2]",
                                       "add\tr1, r1, #61", "ldrb\tr0, [r1]", "mov\tr0, #1",
                                       "strb\tr0, [r1]", "bx\tlr")),
                ("second load before the store", assembly(
                    "ldr\tr1, .L3", "add\tr1, r1, #61", "ldrb\tr2, [r1]", "ldrb\tr0, [r1]",
                    "mov\tr0, #1", "strb\tr0, [r1]", "bx\tlr")),
                ("load of another byte", assembly(
                    "ldr\tr1, .L3", "add\tr1, r1, #61", "ldrb\tr0, [r1, #0]", "sub\tr2, r1, #1",
                    "ldrb\tr2, [r2]", "mov\tr0, #1", "strb\tr0, [r1]", "bx\tlr"))):
            with self.subTest(name=name):
                self.refused(real, stripped, "is a dead load of")

    def test_used_load_the_stripped_compile_lacks_is_refused(self):
        # g(sym.x - sym.x): both loads feed the subtraction; the stripped compile folds it
        real = assembly("push\t{lr}", "ldr\tr1, .L3", "add\tr1, r1, #60", "ldrb\tr0, [r1]",
                        "ldrb\tr2, [r1]", "sub\tr0, r0, r2", "bl\tfunc_0802A2C0", "pop\t{r0}",
                        "bx\tr0")
        stripped = assembly("push\t{lr}", "mov\tr0, #0", "bl\tfunc_0802A2C0", "pop\t{r0}", "bx\tr0")
        self.refused(real, stripped, "the qualifier added a read")

    def test_self_assignment_is_refused(self):
        # sym.x = sym.x (or sym.x |= 0): the stripped compile drops it entirely
        real = assembly("ldr\tr1, .L3", "add\tr0, r1, #0", "add\tr0, r0, #60", "ldrb\tr2, [r0]",
                        "ldrb\tr3, [r0]", "strb\tr2, [r0]", "bx\tlr")
        self.refused(real, assembly("bx\tlr"), "self-assignment")
        # the same pair surviving in both compiles is still refused
        both = assembly("ldr\tr1, .L3", "add\tr0, r1, #60", "ldrb\tr2, [r0]", "strb\tr2, [r0]",
                        "bx\tlr")
        self.refused(both, both, "self-assignment")

    def test_store_without_its_read_modify_write_load_is_refused(self):
        # sym.unknown_02[0x3A] = 1 writes the pinned byte through a plain alias
        same = assembly("ldr\tr0, .L3", "add\tr0, r0, #60", "mov\tr1, #1", "strb\tr1, [r0]", "bx\tlr")
        self.refused(same, same, "without the read-modify-write load")

    def test_changed_schedule_or_behaviour_is_refused(self):
        real = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "ldrb\tr0, [r1]", "mov\tr0, #1",
                        "strb\tr0, [r1]", "ldrb\tr0, [r1, #1]", "mov\tr0, #2", "strb\tr0, [r1, #1]",
                        "bx\tlr")
        swapped = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "mov\tr0, #2", "strb\tr0, [r1, #1]",
                           "mov\tr0, #1", "strb\tr0, [r1]", "bx\tlr")
        self.refused(real, swapped, "differ in observable behaviour")
        other_value = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "mov\tr0, #1", "strb\tr0, [r1]",
                               "mov\tr0, #3", "strb\tr0, [r1, #1]", "bx\tlr")
        self.refused(real, other_value, "differ in observable behaviour")
        stores_more = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "mov\tr0, #1", "strb\tr0, [r1]",
                               "mov\tr0, #2", "strb\tr0, [r1, #1]", "strb\tr0, [r1, #1]", "bx\tlr")
        self.refused(real, stores_more, "differ in observable behaviour")
        branchy = assembly("ldr\tr1, .L3", "cmp\tr0, #0", "beq\t.L9", "add\tr1, r1, #60",
                           "ldrb\tr2, [r1]", "mov\tr2, #1", "strb\tr2, [r1]", ".L9:", "bx\tlr")
        plain = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", "mov\tr2, #1", "strb\tr2, [r1]",
                         "bx\tlr")
        self.refused(branchy, plain, "stripped compile")

    def test_read_modify_write_load_must_sit_next_to_its_store(self):
        # review repro p2/08000002: a planted read, then the value's arithmetic,
        # then a store to the pinned byte; the store borrows the planted load
        real = assembly("add\tr3, r0, #0", "ldr\tr0, .L3", "add\tr0, r0, #60", "ldrb\tr2, [r0]",
                        "mul\tr1, r1, r3", "add\tr3, r1, #7", "strb\tr3, [r0]", "bx\tlr")
        stripped = assembly("add\tr2, r0, #0", "mov\tr0, r2", "mul\tr0, r0, r1", "add\tr2, r0, #7",
                            "ldr\tr0, .L3", "add\tr0, r0, #60", "strb\tr2, [r0]", "bx\tlr")
        self.refused(real, stripped, "is a dead load of")
        # the genuine shape computes the value first (p2b)
        genuine = assembly("add\tr2, r0, #0", "mov\tr0, r2", "mul\tr0, r0, r1", "add\tr2, r0, #7",
                           "ldr\tr0, .L3", "add\tr0, r0, #60", "ldrb\tr1, [r0]", "strb\tr2, [r0]",
                           "bx\tlr")
        self.assertEqual(compare(genuine, stripped)[0][1:], (1, [6], []))
        # a hoisted constant for a later store may sit in between (08050D50)
        hoisted = assembly("ldr\tr1, .L3", "add\tr1, r1, #61", "ldrb\tr0, [r1]", "mov\tr2, #0",
                           "mov\tr0, #19", "strb\tr0, [r1]", "sub\tr1, r1, #1", "ldrb\tr0, [r1]",
                           "strb\tr2, [r1]", "bx\tlr")
        plain = assembly("ldr\tr1, .L3", "add\tr1, r1, #61", "mov\tr2, #0", "mov\tr0, #19",
                         "strb\tr0, [r1]", "sub\tr1, r1, #1", "strb\tr2, [r1]", "bx\tlr")
        self.assertEqual(compare(hoisted, plain)[0][1:], (1, [2, 7], []))

    def test_chained_re_read_needs_the_assignment_shape(self):
        # review repro 08000004: store 3C, unrelated work, then 3D = 3C
        real = assembly("ldr\tr3, .L3", "add\tr2, r3, #60", "ldrb\tr1, [r2]", "strb\tr0, [r2]",
                        "mul\tr0, r0, r0", "strh\tr0, [r3]", "ldrb\tr0, [r2]", "add\tr2, r2, #1",
                        "ldrb\tr1, [r2]", "strb\tr0, [r2]", "bx\tlr")
        stripped = assembly("ldr\tr3, .L3", "add\tr2, r3, #60", "strb\tr0, [r2]", "mov\tr1, r0",
                            "mul\tr1, r1, r1", "strh\tr1, [r3]", "add\tr2, r2, #1", "strb\tr0, [r2]",
                            "bx\tlr")
        with self.assertRaises(semantics.SemanticError) as caught:
            compare(real, stripped)
        self.assertIn("the qualifier added a read", str(caught.exception))

    def test_object_addresses_must_be_constant_member_offsets(self):
        # review repro p1: (&sym)[n].unknown_3C
        indexed = assembly("ldr\tr2, .L3", "mov\tr1, #80", "mul\tr1, r1, r0", "add\tr2, r2, r1",
                           "add\tr2, r2, #60", "ldrb\tr0, [r2]", "bx\tlr")
        self.refused(indexed, assembly("bx\tlr"), "combines g_control_flags_03000940 with other terms")
        outside = assembly("ldr\tr2, .L3", "add\tr2, r2, #80", "mov\tr0, #1", "strb\tr0, [r2]", "bx\tlr")
        self.refused(outside, outside, "lies outside the object")
        multiple = assembly("ldr\tr2, .L3", "ldmia\tr2!, {r0, r1}", "bx\tlr")
        self.refused(multiple, multiple, "multi-register transfer")

    def test_escaping_stack_data_is_compared(self):
        def frame(value, escape):
            return assembly("push\t{lr}", "add\tsp, sp, #-4", f"mov\tr1, #{value}", "mov\tr2, sp",
                            "strb\tr1, [r2]", *escape, "add\tsp, sp, #4", "pop\t{r0}", "bx\tr0")
        through_call = ("mov\tr0, sp", "bl\tfunc_0802A2C0")
        through_store = ("ldr\tr3, .L3", "mov\tr2, sp", "str\tr2, [r3]")
        for escape in (through_call, through_store):
            with self.subTest(escape=escape):
                self.assertEqual(compare(frame(1, escape), frame(1, escape))[0][1], 1)
                self.refused(frame(1, escape), frame(2, escape), "differ in observable behaviour")
        self.assertTrue(semantics.contains(semantics.add(semantics.SP, -4), semantics.SP))

    def test_low_register_move_sets_the_flags(self):
        moved = assembly("mov\tr1, r0", "beq\t.L9", "ldr\tr2, .L3", "add\tr2, r2, #60", "ldrb\tr3, [r2]",
                         "mov\tr3, #1", "strb\tr3, [r2]", ".L9:", "bx\tlr")
        # the stripped compile spells the same copy `add r1, r0, #0`; both set Z
        added = moved.replace("ldrb\tr3, [r2]\n\t", "").replace("mov\tr1, r0", "add\tr1, r0, #0")
        self.assertNotEqual(added, moved.replace("ldrb\tr3, [r2]\n\t", ""))
        self.assertEqual(compare(moved, added)[0][1], 2)

    def test_signatures_come_from_consistent_file_scope_declarations(self):
        scope = semantics.file_scope("extern void g(int);\nint f(u8 a, int b)\n{ if (x) { y(1, 2); } }\n"
                                     "void h(void);\n")
        self.assertEqual([semantics.function_signature(scope, name) for name in ("g", "f", "h", "y")],
                         [(False, 1), (True, 2), (False, 0), (True, None)])
        with self.assertRaises(semantics.SemanticError):
            semantics.function_signature(semantics.file_scope("void g(int);\nint g(int, int);\n"), "g")

    def test_unmodelled_code_fails_closed(self):
        loop = assembly("ldr\tr1, .L3", "add\tr1, r1, #60", ".L9:", "ldrb\tr2, [r1]", "mov\tr2, #1",
                        "strb\tr2, [r1]", "sub\tr0, r0, #1", "cmp\tr0, #0", "bne\t.L9", "bx\tlr")
        self.refused(loop, loop, "unknown branch conditions")
        computed = assembly("mov\tpc, r0")
        self.refused(computed, computed, "computed jumps")
        self.refused(assembly("bx\tlr"), assembly("bx\tlr", name="func_08028C38"),
                     "define different functions")


class ReportRecordTests(unittest.TestCase):
    USES = "* allowlisted volatile: `g_control_flags_03000940` at `0x03000940` declared in x"
    SEMANTICS = semantics.record(SYMBOL, [("func_08028C34", 1, [2, 6], [])])

    def report(self, *records):
        return "\n".join(("* verification: x",) + records + ("", "**MATCH - byte identical** - 4/4 bytes", ""))

    def matches(self, report, semantic_records=None, error=None):
        def fresh(root, address):
            if error is not None:
                raise error
            return [self.SEMANTICS] if semantic_records is None else semantic_records

        import unsigned_divmod_profile
        with mock.patch.object(plausible, "allowlisted_volatile_uses", return_value=[self.USES]), \
                mock.patch.object(match, "allowlisted_volatile_semantics", side_effect=fresh), \
                mock.patch.object(unsigned_divmod_profile, "selected", return_value=True), \
                mock.patch.object(unsigned_divmod_profile, "report_matches", return_value=True):
            return match_evidence.report_matches(report, "/nonexistent", 0x08028C34)

    def test_semantic_record_is_recomputed_and_must_be_unaltered(self):
        self.assertTrue(self.matches(self.report(self.USES, self.SEMANTICS)))
        self.assertFalse(self.matches(self.report(self.USES)))
        self.assertFalse(self.matches(self.report(self.USES, self.SEMANTICS.replace("[3, 7]", "[3]"))))
        self.assertFalse(self.matches(self.report(self.USES, self.SEMANTICS, self.SEMANTICS)))
        self.assertFalse(self.matches(self.report(self.USES, self.SEMANTICS),
                                      semantic_records=[self.SEMANTICS.replace("1 path", "2 paths")]))
        self.assertFalse(self.matches(self.report(self.USES, self.SEMANTICS),
                                      error=semantics.SemanticError("dead load")))
        self.assertFalse(self.matches(self.report(self.USES, self.SEMANTICS),
                                      error=RuntimeError("cc1 failed")))


HEADER = ("#ifndef CONTROL_FLAGS_H\n#define CONTROL_FLAGS_H\n"
          "typedef unsigned char u8;\ntypedef unsigned short u16;\n{declaration}\n#endif\n")


@unittest.skipUnless(Path(os.path.expandvars(match.DEFAULT_CC)).is_file() and
                     shutil.which("cpp") and shutil.which("arm-none-eabi-as") and
                     shutil.which("arm-none-eabi-objcopy"), "fixed compiler required")
class CompiledSemanticTests(unittest.TestCase):
    """the real check through agbcc: the recoveries pass and the plants do not"""

    @classmethod
    def setUpClass(cls):
        cls.directory = tempfile.TemporaryDirectory()
        cls.root = Path(cls.directory.name)
        entry = plausible.volatile_allow_entries()[0]
        for name in ("config", "src", "include"):
            (cls.root / name).mkdir()
        (cls.root / "config" / "data_symbols.json").write_text(
            json.dumps({entry["symbol"]: entry["address"]}))
        declaration = entry["declaration"].replace("; ", ";\n    ")
        (cls.root / entry["header"]).write_text(HEADER.format(declaration=declaration))

    @classmethod
    def tearDownClass(cls):
        cls.directory.cleanup()

    def check(self, body, parameters="void"):
        (self.root / "src" / "08028C34.c").write_text(
            '#include "control_flags.h"\nextern void func_0802A2C0(u8, u8, u8, u8);\n'
            f"void func_08028C34({parameters})\n{{\n" + body + "\n}\n")
        return match.allowlisted_volatile_semantics(self.root, 0x08028C34)

    def test_recovered_bodies_pass(self):
        s = SYMBOL
        for body in (f"{s}.unknown_43 = 0x13; {s}.unknown_3D = 0x10; {s}.unknown_41 = 8; "
                     f"{s}.unknown_3C = 0xE0; {s}.unknown_40 = 0x20; {s}.display |= 0x4000; "
                     "func_0802A2C0(2, 2, 0x1A, 6);",
                     f"{s}.unknown_4A = ({s}.unknown_4B = 0); {s}.unknown_4C = ({s}.unknown_4D = 0);"):
            with self.subTest(body=body):
                (record,) = self.check(body)
                self.assertTrue(record.startswith("* allowlisted volatile semantics: "), record)

    def test_plants_are_refused(self):
        s, tail = SYMBOL, f" {SYMBOL}.unknown_3D = 1;"
        for plant, reason in ((f"({s}.unknown_3C, 0);", "dead load"),
                              (f"{s}.unknown_3C |= 0;", "self-assignment"),
                              (f"{s}.unknown_3C = {s}.unknown_3C;", "self-assignment"),
                              (f"{{ u8 unused = {s}.unknown_3C; }}", "dead load"),
                              (f"if ({s}.unknown_3C) ;", "dead load"),
                              (f"func_0802A2C0(0 * {s}.unknown_3C, 0, 0, 0);", "dead load"),
                              (f"{s}.unknown_3C;", "dead load"),
                              (f"(void){s}.unknown_3C;", "dead load"),
                              (f"!{s}.unknown_3C;", "dead load"),
                              (f"{s}.unknown_02[0x3A] = 1;", "without the read-modify-write load")):
            with self.subTest(plant=plant):
                with self.assertRaises(semantics.SemanticError) as caught:
                    self.check(plant + tail)
                self.assertIn(reason, str(caught.exception))

    def test_review_repros_are_refused(self):
        s = SYMBOL
        for name, parameters, body, reason in (
                ("p1", "int n, int a", f"(void)(&{s})[n].unknown_3C;", "combines"),
                ("08000002", "int a, int b",
                 f"(void){s}.unknown_3C; a = a * b + 7; {s}.unknown_02[0x3A] = a;", "dead load"),
                ("08000003", "int a, int b, int c",
                 f"(void){s}.unknown_43; a = (a * b + 7) ^ (c << 3); b = a * c; {s}.unknown_44[-1] = b;",
                 "dead load"),
                ("08000004", "int a, int b, int c, int d",
                 f"{s}.unknown_3C = a; {s}.display = b * c + d * a + (b ^ d) * c; "
                 f"{s}.unknown_3D = {s}.unknown_3C;", "the qualifier added a read")):
            with self.subTest(repro=name):
                with self.assertRaises(semantics.SemanticError) as caught:
                    self.check(body, parameters)
                self.assertIn(reason, str(caught.exception))
        (record,) = self.check(f"a = a * b + 7; {s}.unknown_3C = a;", "int a, int b")
        self.assertIn("read-modify-write loads at [7]", record)


